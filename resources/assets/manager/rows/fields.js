// One field of the row editor, for any column type.

import { BOOT, PG } from '../boot.js';
import { base64ToBytes, bytesToHex, download, fileToBase64 } from '../lib/files.js';
import { formatBytes, formatNumber } from '../lib/format.js';
import { typeName } from '../structure/types.js';
import { btn, check, fill, h, put, select } from '../ui/dom.js';
import { icon } from '../ui/icons.js';
import { menu } from '../ui/popovers.js';
import { toast } from '../ui/toasts.js';
import { NUMERIC_CATEGORIES, boolOut, isBinary, isTrue, isTruncated, plainValue } from '../values.js';

/**
 * One field of the row editor. output(): the value to send — a string, null, {default}, {expr}, {x} (hex) or {b} (base64);
 * undefined leaves the column out.
 */
export function makeField(c, initial, { creating, readonly, isKey, preset, onchange }) {
  // state: mode value | null | expr | default
  let mode = 'value';
  let value = '';
  let expr = '';
  let touched = false;
  let invalid = false;
  let binNew = null; // {x} or {b}
  if (!creating) {
    if (initial === null) mode = 'null';
    else if (isBinary(initial)) value = initial;
    else if (isTruncated(initial)) value = initial;
    else value = String(initial);
  } else if (preset !== undefined) {
    touched = true;
    if (preset === null) mode = 'null';
    else if (typeof preset === 'object' && preset.expr) {
      mode = 'expr';
      expr = preset.expr;
    } else if (isBinary(preset)) {
      binNew = { b: preset.b };
      value = preset;
    } else value = String(preset);
  }
  const startMode = mode,
    startValue = value;
  const cut = isTruncated(initial);
  const locked = readonly || c.generated || cut;
  const el = h('div', { class: 'field-row' });
  const tools = h('div', { class: 'fr-tools' });
  const badges = [];
  if (isKey) badges.push(h('span', { class: 'badge pk' }, icon('key'), 'key'));
  if (c.default.kind === 'auto') badges.push(h('span', { class: 'badge' }, PG ? 'identity' : 'auto increment'));
  if (c.generated) badges.push(h('span', { class: 'badge' }, 'generated'));
  if (!c.nullable && c.default.kind === 'none')
    badges.push(h('span', { class: 'badge', title: 'NOT NULL without a default' }, 'required'));
  put(
    el,
    h(
      'div',
      { class: 'fr-head' },
      h('span', { class: 'fr-name', title: c.name }, c.name),
      h('span', { class: 'fr-type', title: c.type }, typeName(c)),
      badges,
      tools,
    ),
  );
  const holder = h('div');
  const note = h('div', { class: 'note' });
  put(el, holder, note);
  if (c.comment) note.textContent = c.comment;

  const defaultText = () => {
    const k = c.default.kind;
    if (k === 'auto') return PG ? 'Generated by the identity' : 'Next auto-increment value';
    if (k === 'generated') return 'Computed by the database';
    if (k === 'literal') return `Default: ${c.default.value}`;
    if (k === 'expr') return `Default: ${c.default.value}`;
    if (k === 'null') return 'Default: NULL';
    return c.nullable ? 'Default: NULL' : 'No default — a value is required';
  };

  function changed() {
    if (locked) return false;
    if (creating) return touched;
    if (mode !== startMode) return true;
    if (mode === 'value') return binNew !== null || value !== startValue;
    return mode === 'expr' || mode === 'default';
  }
  function setMode(m) {
    mode = m;
    touched = true;
    draw();
    onchange();
  }
  function output() {
    if (locked) return undefined;
    if (creating && !touched) return undefined;
    if (mode === 'null') return null;
    if (mode === 'default') return { default: true };
    if (mode === 'expr') return { expr };
    if (c.cat === 'bin') return binNew ?? undefined;
    return value;
  }

  function draw() {
    el.classList.toggle('changed', changed());
    fill(tools);
    if (!locked) {
      if (c.nullable)
        put(
          tools,
          check('NULL', mode === 'null', (on) => setMode(on ? 'null' : 'value')),
        );
      put(
        tools,
        h(
          'button',
          {
            type: 'button',
            class: 'btn ghost sm icon',
            title: 'Set to a function or DEFAULT',
            onclick: (e) =>
              menu(
                e.currentTarget,
                [
                  {
                    label: 'DEFAULT',
                    icon: 'zap',
                    onClick: () => setMode('default'),
                    hint: c.default.kind !== 'none' ? String(c.default.value ?? c.default.kind) : '',
                  },
                  { sep: true },
                  ...BOOT.functions.map((fn) => ({
                    label: fn,
                    onClick: () => {
                      expr = fn;
                      setMode('expr');
                    },
                  })),
                  creating && touched ? { sep: true } : null,
                  creating && touched
                    ? {
                        label: 'Leave out (use the default)',
                        onClick: () => {
                          touched = false;
                          mode = 'value';
                          value = '';
                          binNew = null;
                          draw();
                          onchange();
                        },
                      }
                    : null,
                ].filter(Boolean),
              ),
          },
          icon('zap'),
        ),
      );
    }
    fill(holder);
    if (c.generated) {
      put(
        holder,
        h(
          'div',
          { class: 'input mono', style: 'display:flex;align-items:center;opacity:.75' },
          value === '' && mode === 'null' ? 'NULL' : (plainValue(initial) ?? 'NULL'),
        ),
      );
      note.textContent = c.expression ? `= ${c.expression}` : 'Generated column';
      return;
    }
    if (mode === 'null') {
      put(
        holder,
        h('div', { class: 'input', style: 'display:flex;align-items:center' }, h('span', { class: 'v-null' }, 'NULL')),
      );
      return;
    }
    if (mode === 'default') {
      put(
        holder,
        h(
          'div',
          { class: 'input', style: 'display:flex;align-items:center;gap:8px' },
          h('span', { class: 'badge solid' }, 'DEFAULT'),
          h('span', { class: 'muted small' }, defaultText()),
        ),
      );
      return;
    }
    if (mode === 'expr') {
      put(
        holder,
        h(
          'div',
          { class: 'input mono', style: 'display:flex;align-items:center;gap:8px' },
          icon('zap'),
          expr,
          h('span', { class: 'grow' }),
          h('button', { type: 'button', class: 'btn ghost sm', onclick: () => setMode('value') }, 'Type a value'),
        ),
      );
      return;
    }
    if (cut) {
      put(holder, h('textarea', { class: 'input mono', rows: 6, readOnly: true, value: initial.t }));
      note.textContent = `This value has ${formatNumber(initial.n)} characters — too long to edit here. Use the SQL console to change it.`;
      return;
    }
    put(holder, control());
  }

  function control() {
    const ph = creating && !touched ? defaultText() : '';
    const onInput = (v) => {
      value = v;
      touched = true;
      el.classList.toggle('changed', changed());
      onchange();
    };
    if (c.cat === 'bin') return binControl();
    if (c.cat === 'bool') {
      const sel = select(
        [
          ['', creating && !touched ? ph : '—'],
          [boolOut(true), 'true'],
          [boolOut(false), 'false'],
        ],
        creating && !touched ? '' : value === '' ? '' : boolOut(isTrue(value)),
        {
          disabled: readonly,
          onchange: (e) => onInput(e.target.value),
        },
      );
      return sel;
    }
    if (c.cat === 'enum' && Array.isArray(c.options)) {
      return select(
        [['', creating && !touched ? ph : '—'], ...c.options.map((o) => [o, o])],
        creating && !touched ? '' : value,
        { disabled: readonly, onchange: (e) => onInput(e.target.value) },
      );
    }
    if (c.cat === 'set' && Array.isArray(c.options)) {
      const on = new Set(value === '' ? [] : value.split(','));
      return h(
        'div',
        { class: 'row', style: 'flex-wrap:wrap;gap:12px' },
        c.options.map((o) =>
          check(o, on.has(o), (v) => {
            v ? on.add(o) : on.delete(o);
            onInput(c.options.filter((x) => on.has(x)).join(','));
          }),
        ),
      );
    }
    const multi =
      (['text', 'json', 'geo', 'array', 'other'].includes(c.cat) &&
        (c.cat !== 'other' || value.length > 60 || /\n/.test(value))) ||
      (c.cat === 'str' && (value.length > 80 || /\n/.test(value) || (c.max ?? 0) > 255));
    const mono = ['json', 'geo', 'vector', 'array', 'other', 'bin'].includes(c.cat);
    const placeholders = {
      date: 'YYYY-MM-DD',
      datetime: 'YYYY-MM-DD HH:MM:SS',
      time: 'HH:MM:SS',
      year: 'YYYY',
      json: '{"key": "value"}',
      geo: 'POINT(1 2)',
      vector: '[1, 2, 3]',
      array: '{1,2,3}',
    };
    const props = {
      class: 'input' + (mono ? ' mono' : ''),
      value,
      placeholder: ph || placeholders[c.cat] || '',
      readOnly: readonly,
      spellcheck: false,
      dir: 'auto',
      'aria-label': c.name,
    };
    if (NUMERIC_CATEGORIES.has(c.cat)) props.inputmode = 'decimal';
    const el2 = multi
      ? h('textarea', {
          ...props,
          rows:
            c.cat === 'json'
              ? Math.min(14, Math.max(4, value.split('\n').length + 1))
              : Math.min(10, Math.max(3, Math.ceil(value.length / 60))),
        })
      : h('input', { ...props, type: 'text' });
    el2.addEventListener('input', () => {
      onInput(el2.value);
      if (c.cat === 'json') validateJson();
    });
    if (c.cat !== 'json') return el2;
    const status = h('span', { class: 'small muted' });
    const validateJson = () => {
      if (el2.value.trim() === '') {
        invalid = false;
        status.textContent = '';
        return;
      }
      try {
        JSON.parse(el2.value);
        invalid = false;
        status.textContent = 'Valid JSON';
        status.style.color = 'var(--success)';
      } catch (err) {
        invalid = true;
        status.textContent = 'Invalid JSON: ' + err.message;
        status.style.color = 'var(--destructive)';
      }
    };
    validateJson();
    return h(
      'div',
      { class: 'stack', style: 'gap:6px' },
      el2,
      h(
        'div',
        { class: 'row' },
        status,
        h('span', { class: 'grow' }),
        readonly
          ? null
          : h(
              'button',
              {
                type: 'button',
                class: 'btn ghost sm',
                onclick: () => {
                  try {
                    el2.value = JSON.stringify(JSON.parse(el2.value), null, 2);
                    el2.rows = Math.min(14, Math.max(4, el2.value.split('\n').length + 1));
                    onInput(el2.value);
                    validateJson();
                  } catch {
                    validateJson();
                  }
                },
              },
              'Format',
            ),
      ),
    );
  }

  function binControl() {
    const cur = binNew ? binNew : isBinary(value) ? value : null;
    const info = h('span', { class: 'v-bin' });
    const describe = () => {
      if (binNew && 'x' in binNew) info.textContent = `${formatBytes(binNew.x.length / 2)} (edited)`;
      else if (binNew && 'b' in binNew) info.textContent = `${formatBytes(atob(binNew.b).length)} (new file)`;
      else if (cur)
        info.textContent = cur.n
          ? `0x${bytesToHex(base64ToBytes(cur.b), 16).toUpperCase()}${cur.n > 16 ? '…' : ''} · ${formatBytes(cur.n)}`
          : '0 bytes';
      else info.textContent = creating ? 'No value' : '0 bytes';
    };
    describe();
    const file = h('input', {
      type: 'file',
      class: 'hidden',
      onchange: async () => {
        const f = file.files[0];
        if (!f) return;
        if (f.size > 16 * 1024 * 1024) {
          toast('Choose a file of at most 16 MB.', 'err');
          return;
        }
        binNew = { b: await fileToBase64(f) };
        touched = true;
        describe();
        draw();
        onchange();
      },
    });
    const actions = h('div', { class: 'row', style: 'flex-wrap:wrap' });
    if (!readonly) {
      put(
        actions,
        btn('Upload file', () => file.click(), 'sm', 'upload'),
      );
      const small = !cur || cur.n <= 65536;
      if (small)
        put(
          actions,
          btn(
            'Edit as hex',
            () => {
              const hex = binNew && 'x' in binNew ? binNew.x : cur ? bytesToHex(base64ToBytes(cur.b)) : '';
              const ta = h('textarea', { class: 'input mono', rows: 6, value: hex, spellcheck: false });
              fill(holder, ta, h('div', { class: 'note' }, 'Hexadecimal digits; spaces are ignored.'));
              ta.focus();
              ta.addEventListener('input', () => {
                const clean = ta.value.replace(/\s+/g, '').replace(/^0x/i, '');
                invalid = !/^(?:[0-9a-fA-F]{2})*$/.test(clean);
                ta.style.borderColor = invalid ? 'var(--destructive)' : '';
                if (!invalid) {
                  binNew = { x: clean.toLowerCase() };
                  touched = true;
                  el.classList.toggle('changed', changed());
                  onchange();
                }
              });
            },
            'sm',
            'code',
          ),
        );
    }
    if (cur && cur.n) {
      put(
        actions,
        btn('Download', () => download(new Blob([base64ToBytes(cur.b)]), `${c.name}.bin`), 'sm', 'download'),
      );
    }
    return h(
      'div',
      { class: 'stack', style: 'gap:8px' },
      h('div', { class: 'input', style: 'display:flex;align-items:center' }, info),
      actions,
      file,
    );
  }

  draw();
  return { c, el, changed, output, touched: () => touched, invalid: () => invalid && mode === 'value' };
}
